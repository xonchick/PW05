#include <stdio.h>

//Числа пелля Pn= 2*Pn-1+Pn-2
int pell(int n)
    {
        if (n == 0)
        {
            return 0;
        }
        if (n == 1)
        {
            return 1;
        }
        return 2*pell(n-1)+pell(n-2);
    }

//индексация в массивах начинается с 0, тк 0 - это тоже число
int main()
{
    double a[8];
    for (int i=0;i<8;i++)
    {
        a[i]=pell(i);
        printf("%.2f ", a[i]);
    }
    printf("\n");
    printf("%.2f", a[7]);
    //надо было найти и вывести максимум. По формуле пелля число увеличивается с каждым разом
    //поэтому максимальное число - последнее число последовательности

}

